# Función para evaluar una condición simple
#---------------------------------------------------------

def evaluar_condicion(texto):

    texto = texto.strip()

    #-----------------------------------------
    # C=valor
    #-----------------------------------------

    if "=" in texto:

        c, valor_esperado = texto.split("=", 1)

        c = c.strip()

        valor_esperado = valor_esperado.strip().lower()

        r = obtener(c)


        if r is None:
            return False

        # Manejar respuestas tipo lista (ej. selección múltiple)
        if isinstance(r, list):

            # Si la regla espera 'Sí'
            if valor_esperado == 'sí':
                # Es True si la lista no está vacía y no contiene solo 'Ninguno'
                return bool(r) and 'ninguno' not in [str(item).lower() for item in r]

            # Si la regla espera 'No'
            elif valor_esperado == 'no':
                # Es True si la lista está vacía o contiene solo 'Ninguno'
                return not bool(r) or ('ninguno' in [str(item).lower() for item in r] and len(r) == 1)

            # Para otros valores específicos esperados en una lista
            else:
                return valor_esperado in [str(item).lower() for item in r]

        # Manejar respuestas de cadena simple
        else:

            response_lower = str(r).lower()

            if valor_esperado == 'sí':
                # Chequear por 'sí' o 'sospecha' directas
                if response_lower == 'sí' or response_lower == 'sospecha':
                    return True
                # Manejo especial para C011=Sí si la respuesta es 'sobrepeso' u 'obesidad'
                if c == 'C011' and (response_lower == 'sobrepeso' or response_lower == 'obesidad'):
                    return True
                return False

            elif valor_esperado == 'no':
                return response_lower == 'no'

            # Para otros valores específicos (ej. CXXX=Sobrepeso)
            else:
                return response_lower == valor_esperado

    #-----------------------------------------
    # C contiene xxx
    #-----------------------------------------

    if "contiene" in texto.lower():

        partes = re.split(
            r"contiene",
            texto,
            flags=re.IGNORECASE
        )

        c = partes[0].strip()

        valor = partes[1].strip()

        r = obtener(c)


        if r is None:
            return False

        if isinstance(r,list):

            return any(
                valor.lower() in str(x).lower()
                for x in r
            )

        return valor.lower() in str(r).lower()

    #-----------------------------------------
    # C incluye xxx
    #-----------------------------------------

    if "incluye" in texto.lower():

        partes = re.split(
            r"incluye",
            texto,
            flags=re.IGNORECASE
        )

        c = partes[0].strip()

        valor = partes[1].strip()

        r = obtener(c)


        if r is None:
            return False

        if isinstance(r,list):

            return any(
                valor.lower() in str(x).lower()
                for x in r
            )

        return valor.lower() in str(r).lower()

    return False

