def normalizar_texto_restriccion(texto):

    if pd.isna(texto):
        return ""

    texto = str(texto).lower()
    texto = unidecode(texto)

    texto = texto.replace("-", " ")
    texto = texto.replace("_", " ")
    texto = " ".join(texto.split())

    return texto


# ============================================================
