# ============================================================

def buscar_restriccion(query):

    consulta = normalizar_texto_restriccion(query)

    if not consulta:
        return []

    resultados = []

    # --------------------------------------------------------
    # Determinar si se está buscando un código
    # --------------------------------------------------------

    codigo = consulta.replace(" ", "")

    es_codigo = (
        codigo.startswith("x")
        and codigo[1:].isdigit()
    )

    # ========================================================
    # BUSQUEDA POR CODIGO
    # ========================================================

    if es_codigo:

        for _, fila in df_restricciones.iterrows():

            id_restriccion = normalizar_texto_restriccion(
                fila["Restriccion_ID"]
            ).replace(" ", "")

            if id_restriccion == codigo:

                resultado = fila.to_dict()

                resultado["Coincidencia"] = 100

                resultados.append(resultado)

                return resultados

        # Si no encontró exactamente el código,
        # buscar códigos similares.

        for _, fila in df_restricciones.iterrows():

            id_restriccion = normalizar_texto_restriccion(
                fila["Restriccion_ID"]
            ).replace(" ", "")

            if not id_restriccion:
                continue

            coincidencia = fuzz.ratio(
                codigo,
                id_restriccion
            )

            if coincidencia >= 80:

                resultado = fila.to_dict()

                resultado["Coincidencia"] = round(
                    coincidencia,
                    1
                )

                resultados.append(resultado)

        resultados.sort(
            key=lambda x: x["Coincidencia"],
            reverse=True
        )

        return resultados[:10]

    # ========================================================
    # BUSQUEDA POR PRODUCTO
    # ========================================================

    for _, fila in df_restricciones.iterrows():

        producto = normalizar_texto_restriccion(
            fila["Producto"]
        )

        if not producto:
            continue

        # Coincidencia directa
        if consulta in producto:

            resultado = fila.to_dict()

            resultado["Coincidencia"] = 100

            resultados.append(resultado)

            continue

        # Coincidencia aproximada
        coincidencia = fuzz.partial_ratio(
            consulta,
            producto
        )

        if coincidencia >= 70:

            resultado = fila.to_dict()

            resultado["Coincidencia"] = round(
                coincidencia,
                1
            )

            resultados.append(resultado)

    # ========================================================
    # SI NO ENCONTRÓ PRODUCTOS,
    # BUSCAR EN EL CONTENIDO DE LAS RESTRICCIONES
    # ========================================================

    if not resultados:

        for _, fila in df_restricciones.iterrows():

            campos = [
                fila.get(
                    "Precaución / Contraindicación",
                    ""
                ),

                fila.get(
                    "Motivo",
                    ""
                ),

                fila.get(
                    "Alternativas seguras",
                    ""
                )
            ]

            mejor = 0

            for campo in campos:

                campo_normalizado = (
                    normalizar_texto_restriccion(
                        campo
                    )
                )

                if not campo_normalizado:
                    continue

                if consulta in campo_normalizado:

                    mejor = 100
                    break

                puntuacion = fuzz.partial_ratio(
                    consulta,
                    campo_normalizado
                )

                if puntuacion > mejor:
                    mejor = puntuacion

            if mejor >= 85:

                resultado = fila.to_dict()

                resultado["Coincidencia"] = round(
                    mejor,
                    1
                )

                resultados.append(resultado)

    # ========================================================
    # ORDENAR
    # ========================================================

    resultados.sort(
        key=lambda x: x["Coincidencia"],
        reverse=True
    )

    return resultados[:10]


