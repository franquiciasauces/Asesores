def buscar_restriccion_por_codigo(consulta):

    codigo = normalizar_restriccion(
        consulta
    ).replace(" ", "")

    resultados = []

    for _, fila in df_restricciones.iterrows():

        codigo_fila = normalizar_restriccion(
            fila.get(
                "Restriccion_ID",
                ""
            )
        ).replace(" ", "")

        if not codigo_fila:
            continue

        # Coincidencia exacta
        if codigo_fila == codigo:

            resultado = fila.to_dict()

            resultado["Coincidencia"] = 100.0

            resultados.append(resultado)

            continue

        # Coincidencia aproximada SOLO entre códigos
        puntuacion = fuzz.ratio(
            codigo,
            codigo_fila
        )

        if puntuacion >= 80:

            resultado = fila.to_dict()

            resultado["Coincidencia"] = round(
                puntuacion,
                1
            )

            resultados.append(resultado)

    resultados.sort(
        key=lambda x: x["Coincidencia"],
        reverse=True
    )

    return resultados


