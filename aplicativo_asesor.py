# ==========================================================
# 1. CONFIGURACION
# ==========================================================

UMBRAL_SEMANTICO = 65.0

UMBRAL_DIRECTO = 82.0

MAX_RESULTADOS_SEMANTICOS = 5


# ==========================================================
# 2. LIMPIAR TEXTO
# ==========================================================

def limpiar_texto_hibrido(texto):

    texto = str(texto)
    texto = texto.lower()
    texto = unidecode(texto)
    texto = texto.strip()

    return texto


