def buscar_sintoma_semantico(
    consulta,
    cantidad_resultados=5
):

    consulta = str(
        consulta
    ).strip()


    if consulta == "":

        return []


    # ------------------------------------------------------
    # Convertir consulta en embedding
    # ------------------------------------------------------

    embedding_consulta = (
        modelo_biomedico.encode(
            [consulta],
            normalize_embeddings=True
        )
    )


    # ------------------------------------------------------
    # Comparar con embeddings guardados
    # ------------------------------------------------------

    similitudes = cosine_similarity(
        embedding_consulta,
        embeddings_sintomas
    )[0]


    # ------------------------------------------------------
    # Obtener mejores posiciones
    # ------------------------------------------------------

    indices = np.argsort(
        similitudes
    )[::-1][
        :cantidad_resultados
    ]


    resultados = []


    for indice in indices:

        puntaje = (
            similitudes[indice] * 100
        )


        if puntaje < UMBRAL_SEMANTICO:

            continue


        fila = (
            df_sintomas_semantica
            .iloc[indice]
        )


        resultados.append({

            "Sintoma_consultado":
                consulta,

            "Sintoma_encontrado":
                fila["Sintoma"],

            "Patologia_ID":
                fila["Patologia_ID"],

            "Patologia":
                fila["Patologia"],

            "Similitud":
                round(
                    puntaje,
                    2
                )
        })


    return resultados


