# ==========================================================

def buscar_sintoma(texto):

    texto_limpio = limpiar_texto(texto)

    if texto_limpio == "":
        return []


    resultados = []


    # ======================================================
    # A. BUSCAR EN EL NOMBRE DE LA PATOLOGÍA
    # ======================================================

    for indice, fila in df_patologias.iterrows():

        nombre_patologia = limpiar_texto(
            fila["Patología"]
        )


        if texto_limpio in nombre_patologia:

            resultados.append({

                "Sintoma":
                    texto,

                "Patologia_ID":
                    fila["Patologia_ID"],

                "Patología":
                    fila["Patología"],

                "Indice":
                    indice,

                "Coincidencia":
                    100.0,

                "Origen":
                    "Nombre de la patología"
            })


    # ======================================================
    # B. BUSCAR EN LOS SÍNTOMAS
    # ======================================================

    for _, fila in df_sintomas.iterrows():

        sintoma = fila[
            "Sintoma_busqueda"
        ]


        if texto_limpio in sintoma:

            resultados.append({

                "Sintoma":
                    fila["Sintoma"],

                "Patologia_ID":
                    fila["Patologia_ID"],

                "Patología":
                    fila["Patología"],

                "Indice":
                    fila["Indice"],

                "Coincidencia":
                    100.0,

                "Origen":
                    "Síntoma"
            })


    # ======================================================
    # C. RAPIDFUZZ COMO APOYO
    # ======================================================

    # Solo se utiliza si no hubo coincidencia directa.

    if len(resultados) == 0:

        sintomas_unicos = (
            df_sintomas[
                "Sintoma_busqueda"
            ]
            .drop_duplicates()
            .tolist()
        )


        coincidencias = process.extract(
            texto_limpio,
            sintomas_unicos,
            scorer=fuzz.token_set_ratio,
            limit=5
        )


        for sintoma_encontrado, puntaje, _ in coincidencias:

            if puntaje >= 85:

                filas = df_sintomas[
                    df_sintomas[
                        "Sintoma_busqueda"
                    ] == sintoma_encontrado
                ]


                for _, fila in filas:

                    resultados.append({

                        "Sintoma":
                            fila["Sintoma"],

                        "Patologia_ID":
                            fila["Patologia_ID"],

                        "Patología":
                            fila["Patología"],

                        "Indice":
                            fila["Indice"],

                        "Coincidencia":
                            round(puntaje, 2),

                        "Origen":
                            "Coincidencia aproximada"
                    })


    # ======================================================
    # D. ELIMINAR DUPLICADOS POR PATOLOGÍA
    # ======================================================

    resultados_por_patologia = {}


    for resultado in resultados:

        pid = resultado[
            "Patologia_ID"
        ]


        if pid not in resultados_por_patologia:

            resultados_por_patologia[pid] = resultado

        else:

            # Conservar la coincidencia más fuerte

            if resultado[
                "Coincidencia"
            ] > resultados_por_patologia[pid][
                "Coincidencia"
            ]:

                resultados_por_patologia[
                    pid
                ] = resultado


    resultados = list(
        resultados_por_patologia.values()
    )


    # ======================================================
    # E. ORDENAR POR FUERZA DE COINCIDENCIA
    # ======================================================

    resultados.sort(
        key=lambda x:
        x["Coincidencia"],
        reverse=True
    )


    return resultados


