def buscar_restriccion_por_producto(consulta):

    resultados = []

    consulta_normalizada = normalizar_restriccion(
        consulta
    )

    for _, fila in df_restricciones.iterrows():

        producto = normalizar_restriccion(
            fila.get(
                "Producto",
                ""
            )
        )

        producto_normalizado = normalizar_restriccion(
            fila.get(
                "Producto_Normalized",
                ""
            )
        )

        if not producto:
            continue

        # --------------------------------------------
        # Coincidencia directa
        # --------------------------------------------

        if (
            consulta_normalizada in producto
            or
            consulta_normalizada in producto_normalizado
        ):

            puntuacion = 100.0

        else:

            # ----------------------------------------
            # Coincidencia aproximada
            # ----------------------------------------

            puntuacion = max(
                fuzz.partial_ratio(
                    consulta_normalizada,
                    producto
                ),
                fuzz.token_set_ratio(
                    consulta_normalizada,
                    producto
                ),
                fuzz.WRatio(
                    consulta_normalizada,
                    producto
                )
            )

        # Solo coincidencias razonables
        if puntuacion >= 70:

            resultado = fila.to_dict()

            resultado["Coincidencia"] = round(
                puntuacion,
                1
            )

            resultados.append(
                resultado
            )

    resultados.sort(
        key=lambda x: x["Coincidencia"],
        reverse=True
    )

    return resultados


