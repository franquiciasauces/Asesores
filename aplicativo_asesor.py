def normalize_product_name(name):

    if pd.isna(name):

        return ""

    name = str(name)

    name = re.sub(
        r' x \d+ (CAP|ML|GR|SOFGELS|PERLAS|TABLETAS|TABS|CAPS|COMPRIMIDOS)',
        '',
        name,
        flags=re.IGNORECASE
    )

    name = re.sub(
        r'\s+',
        ' ',
        name
    )

    return name.strip().upper()



