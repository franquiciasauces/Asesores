df_busqueda_hibrida = df_sintomas_semantica.copy()

df_busqueda_hibrida["Busqueda_limpia"] = (
    df_busqueda_hibrida["Sintoma"]
    .apply(limpiar_texto_hibrido)
)

lista_sintomas_directos = (
    df_busqueda_hibrida["Busqueda_limpia"]
    .drop_duplicates()
    .tolist()
)


# ==========================================================
# 4. BUSQUEDA DIRECTA
# ==========================================================

def buscar_directo_hibrido(consulta):

    consulta_limpia = limpiar_texto_hibrido(
        consulta
    )

    resultados = []


    # ------------------------------------------------------
    # 4.1 COINCIDENCIA EXACTA O CONTENIDA
    # ------------------------------------------------------

    for _, fila in df_busqueda_hibrida.iterrows():

        sintoma_limpio = fila["Busqueda_limpia"]

        if (
            consulta_limpia == sintoma_limpio
            or consulta_limpia in sintoma_limpio
            or sintoma_limpio in consulta_limpia
        ):

            resultados.append({

                "Sintoma_consultado": consulta,

                "Sintoma_encontrado": fila["Sintoma"],

                "Patologia_ID": fila["Patologia_ID"],

                "Patologia": fila["Patologia"],

                "Tipo_coincidencia": "Directa",

                "Similitud": 100.0

            })


    if resultados:

        return resultados


    # ------------------------------------------------------
    # 4.2 COINCIDENCIA APROXIMADA
    # ------------------------------------------------------

    coincidencias = process.extract(
        consulta_limpia,
        lista_sintomas_directos,
        scorer=fuzz.WRatio,
        limit=3
    )


    for coincidencia in coincidencias:

        sintoma_encontrado = coincidencia[0]
        puntaje = coincidencia[1]

        if puntaje < UMBRAL_DIRECTO:

            continue


        filas = df_busqueda_hibrida[
            df_busqueda_hibrida["Busqueda_limpia"]
            == sintoma_encontrado
        ]


        for _, fila in filas.iterrows():

            resultados.append({

                "Sintoma_consultado": consulta,

                "Sintoma_encontrado": fila["Sintoma"],

                "Patologia_ID": fila["Patologia_ID"],

                "Patologia": fila["Patologia"],

                "Tipo_coincidencia":
                    "Directa aproximada",

                "Similitud": round(
                    puntaje,
                    2
                )

            })


    return resultados


